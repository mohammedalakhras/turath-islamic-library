def clean_pdf_page_text(raw_text: str) -> str:
    # استبدال أنماط الشدة المرمزة كهاء بعد لام التعريف (مثل السهماوات -> السّماوات)
    cleaned = re.sub(r"\bال([تثدذرزسشصضطظلن])ه", r"ال\1ّ", raw_text)
    return cleaned

